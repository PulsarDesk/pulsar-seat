//! Pairing and client management for an **unmodified upstream** Sunshine (contracts §7.1
//! option 2, OQ 28).
//!
//! Upstream has no switch to turn its web-UI listener off and no other PIN channel besides
//! stdin. So, until the fork's seat pipe exists, the service (and nothing else) uses the
//! server's own JSON API on `127.0.0.1:<base+1>`:
//!
//! - The listener is the stream server's, not ours. Pulsar Split adds no HTTP server; the
//!   manager never sees a URL or a credential; no browser is opened.
//! - `origin_web_ui_allowed = pc` makes upstream refuse anything but loopback; the firewall
//!   rules never open base+1 ([`crate::firewall::seat_rules`]).
//! - Credentials are random **per server start**, generated by the service, held only in
//!   memory (zeroised on drop), and handed to the server as upstream's salted hash inside
//!   `credentials_file` before launch. Never `--creds` (argv), never env, never logged. An
//!   attacker who can read the seat directory (SYSTEM/Administrators only) gets a hash of a
//!   random 32-character password that is replaced at the next start.
//! - TLS: the real transport ([`crate::win::https`]) pins the certificate the server created
//!   in the seat's `credentials\` folder and rejects anything else; no proxy.
//!
//! Upstream facts used here were checked against the GPL-3 source of the pinned tag
//! `v2026.516.143833` (`src/confighttp.cpp`, `src/httpcommon.cpp`, `src/nvhttp.cpp`,
//! `src/stream.cpp`): routes `POST /api/pin` `{"pin","name"}` (no `pairing_id` at this tag,
//! OQ 22), `GET /api/clients/list` -> `named_certs[{name,uuid,enabled}]`,
//! `POST /api/clients/unpair` `{"uuid"}`, `POST /api/clients/unpair-all`,
//! `POST /api/apps/close`; JSON bodies need `Content-Type: application/json`; requests
//! without `Origin`/`Referer` need no CSRF token; password hash = upper-case hex of
//! SHA-256(password + salt) printed last byte first (upstream `util::hex` default order);
//! `CLIENT CONNECTED` / `CLIENT DISCONNECTED` info log lines. Upstream has no info-level
//! log line for a waiting pair request; at `debug` it logs the request's query
//! (`phrase -- getservercert`), which is the only pending-request signal we can read. The
//! default level stays `info` ([`crate::conf::effective_verbosity`]), so a PIN is submitted
//! even when no request was seen and upstream's answer decides. Log lines are matched
//! anchored to upstream's `[ts]: Level: message` layout ([`scan_log_line`]).

