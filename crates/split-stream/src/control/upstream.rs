    #[test]
    fn pair_flow_success() {
        let http = FakeHttps::default();
        http.push(200, r#"{"named_certs":[{"name":"a","uuid":"1"}],"status":true}"#);
        http.push(200, r#"{"status":true}"#);
        http.push(200, r#"{"named_certs":[{"name":"a","uuid":"1"}],"status":true}"#);
        http.push(200, r#"{"named_certs":[{"name":"a","uuid":"1"},{"name":"TV","uuid":"2"}],"status":true}"#);
        let log = VecLog::default();
        log.push("[t]: Debug: phrase -- getservercert");
        let mut u = ui(http.clone(), log);
        let ev = u.next_event(Duration::ZERO).unwrap().unwrap();
        let ServerEvent::PairPending { request_id, .. } = ev else { panic!("{ev:?}") };
        assert!(u.status().unwrap().pair_pending);
        let uuid = u.pair_submit(Some(request_id), &Secret("1234".into()), "TV").unwrap();
        assert_eq!(uuid, "2");
        assert_eq!(
            u.next_event(Duration::ZERO).unwrap(),
            Some(ServerEvent::PairEnded { request_id, result: PairResult::Paired })
        );
        let reqs = http.requests();
        assert_eq!(reqs[1].0, "POST");
        assert_eq!(reqs[1].1, "/api/pin");
        let body: serde_json::Value = serde_json::from_slice(reqs[1].2.as_ref().unwrap()).unwrap();
        assert_eq!(body, serde_json::json!({"pin":"1234","name":"TV"}));
    }

    #[test]
    fn pair_flow_wrong_pin_and_no_pending() {
        let http = FakeHttps::default();
        let list = r#"{"named_certs":[],"status":true}"#;
        http.push(200, list);
        http.push(200, r#"{"status":true}"#);
        for _ in 0..3 {
            http.push(200, list);
        }
        http.push(200, list);
        http.push(200, r#"{"status":false}"#);
        // `Some(id)` with no request seen in the log is still submitted (info level).
        http.push(200, list);
        http.push(200, r#"{"status":false}"#);
        let mut u = ui(http, VecLog::default());
        assert_eq!(u.pair_submit(None, &Secret("1234".into()), "TV").unwrap_err(), StreamError::WrongPin);
        assert_eq!(u.pair_submit(None, &Secret("1234".into()), "TV").unwrap_err(), StreamError::NoPendingRequest);
        assert_eq!(u.pair_submit(Some(9), &Secret("1234".into()), "TV").unwrap_err(), StreamError::NoPendingRequest);
        assert!(u.pair_submit(None, &Secret("12a4".into()), "TV").is_err());
        assert!(u.pair_submit(None, &Secret("1234".into()), "").is_err());
    }

