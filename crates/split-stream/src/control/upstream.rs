/// Web-UI user name written into `credentials_file`.
pub const WEB_UI_USER: &str = "pulsar-split-service";
const ALNUM: &[u8; 62] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";

/// Cryptographic random bytes. Real impl: `crate::win::SystemRandom` (BCryptGenRandom).
pub trait Random: Send + Sync {
    fn fill(&self, buf: &mut [u8]) -> Result<(), StreamError>;
}

/// Loopback HTTPS to the seat server's web-UI port. The implementation owns the address
/// (always `127.0.0.1`), the pinned certificate and the Basic-auth credentials, so neither
/// the password nor the header ever passes through this module's callers.
pub trait HttpsLoopback: Send {
    fn request(&mut self, method: &str, path: &str, body: Option<&[u8]>) -> Result<(u16, Vec<u8>), StreamError>;
}

/// Per-start web-UI credentials. `Debug` never shows the password.
pub struct WebUiCredentials {
    pub user: String,
    pub password: Zeroizing<String>,
    pub salt: [u8; 16],
}

impl std::fmt::Debug for WebUiCredentials {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("WebUiCredentials").field("user", &self.user).finish_non_exhaustive()
    }
}

impl WebUiCredentials {
    /// 32 random alphanumeric characters (~190 bits) and a random salt.
    pub fn generate(rng: &dyn Random) -> Result<Self, StreamError> {
        let mut raw = Zeroizing::new([0u8; 32]);
        rng.fill(raw.as_mut())?;
        let mut salt = [0u8; 16];
        rng.fill(&mut salt)?;
        let password: Zeroizing<String> =
            Zeroizing::new(raw.iter().map(|b| ALNUM[(*b as usize) % ALNUM.len()] as char).collect());
        Ok(Self { user: WEB_UI_USER.into(), password, salt })
    }
}

/// Upstream stores the salt as a 16-character string; ours maps random bytes to [A-Za-z0-9].
pub fn salt_string(salt: &[u8; 16]) -> String {
    salt.iter().map(|b| ALNUM[(*b as usize) % ALNUM.len()] as char).collect()
}

/// Upstream's stored password: SHA-256(password + salt) as upper-case hex, last byte first.
pub fn password_hash(password: &str, salt: &str) -> String {
    let mut input = Zeroizing::new(Vec::with_capacity(password.len() + salt.len()));
    input.extend_from_slice(password.as_bytes());
    input.extend_from_slice(salt.as_bytes());
    let digest = Sha256::digest(&input[..]);
    const D: &[u8; 16] = b"0123456789ABCDEF";
    let mut s = String::with_capacity(64);
    for b in digest.iter().rev() {
        s.push(D[(b >> 4) as usize] as char);
        s.push(D[(b & 15) as usize] as char);
    }
    s
}

/// A fresh `credentials_file` document (upstream format: `username`, `salt`, `password`).
pub fn web_ui_credentials_file(user: &str, password: &Secret, salt: &[u8; 16]) -> String {
    merge_web_ui_credentials(None, user, &password.0, salt).expect("fresh document")
}

/// Write the credential keys into an existing `state.json` (same file as `file_state`),
/// keeping `root` (pairing state). Refuses to touch a file that does not parse, so a broken
/// file is never silently replaced and pairings are never lost.
pub fn merge_web_ui_credentials(
    existing: Option<&[u8]>,
    user: &str,
    password: &str,
    salt: &[u8; 16],
) -> Result<String, StreamError> {
    let mut doc = match existing {
        Some(b) if !b.iter().all(u8::is_ascii_whitespace) => match serde_json::from_slice::<serde_json::Value>(b) {
            Ok(serde_json::Value::Object(m)) => m,
            _ => return Err(StreamError::invalid("state.json", "exists but is not a JSON object")),
        },
        _ => serde_json::Map::new(),
    };
    let salt = salt_string(salt);
    doc.insert("username".into(), user.into());
    doc.insert("password".into(), password_hash(password, &salt).into());
    doc.insert("salt".into(), salt.into());
    Ok(serde_json::to_string_pretty(&serde_json::Value::Object(doc)).expect("json"))
}

/// New log lines since the last call.
pub trait LogSource: Send {
    fn read_new(&mut self) -> Vec<String>;
}

/// Tails `server.log`. Handles rotation/truncation (file shorter than the offset -> restart).
pub struct FileTail {
    path: PathBuf,
    offset: u64,
    partial: String,
}

impl FileTail {
    /// Starts at the current end of the file (old lines are not replayed).
    pub fn new(path: PathBuf) -> Self {
        let offset = std::fs::metadata(&path).map(|m| m.len()).unwrap_or(0);
        Self { path, offset, partial: String::new() }
    }

    pub fn from_start(path: PathBuf) -> Self {
        Self { path, offset: 0, partial: String::new() }
    }
}

impl LogSource for FileTail {
    fn read_new(&mut self) -> Vec<String> {
        let Ok(mut f) = std::fs::File::open(&self.path) else {
            return Vec::new();
        };
        let len = f.metadata().map(|m| m.len()).unwrap_or(0);
        if len < self.offset {
            self.offset = 0;
            self.partial.clear();
        }
        if len == self.offset || f.seek(SeekFrom::Start(self.offset)).is_err() {
            return Vec::new();
        }
        let mut buf = Vec::new();
        // At most 1 MiB per call; the rest comes next time.
        let n = f.take(1024 * 1024).read_to_end(&mut buf).unwrap_or(0);
        self.offset += n as u64;
        self.partial.push_str(&String::from_utf8_lossy(&buf[..n]));
        let mut lines: Vec<String> = self.partial.split('\n').map(|l| l.trim_end_matches('\r').to_string()).collect();
        self.partial = lines.pop().unwrap_or_default();
        lines.retain(|l| !l.is_empty());
        lines
    }
}

/// What a log line means for the upstream path.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LogSignal {
    ClientConnected,
    ClientDisconnected,
    /// `received_at` = the line's `[...]` timestamp when present.
    PairRequest { received_at: String },
}

/// Splits an upstream log line `[<timestamp>]: <Level>: <message>` into
/// `(timestamp, level, message)`. `None` for any other layout (continuation lines, text
/// after an injected newline without a full prefix). Same layout rule as
/// `split_audio::scan_log_line` (audio-9); shared here so both can use one parser.
pub fn split_log_line(line: &str) -> Option<(&str, &str, &str)> {
    let line = line.trim_end_matches(['\r', '\n']);
    let rest = line.strip_prefix('[')?;
    let (ts, rest) = rest.split_once("]: ")?;
    if ts.is_empty() || ts.contains(']') || ts.contains('[') {
        return None;
    }
    let (level, msg) = rest.split_once(": ")?;
    const LEVELS: &[&str] = &["Verbose", "Debug", "Info", "Warning", "Error", "Fatal"];
    LEVELS.contains(&level).then_some((ts, level, msg))
}

/// Anchored match: the whole message must equal upstream's fixed text at the expected
/// level. The log also carries text that clients control (device / app names, and at
/// `debug` the query values of unauthenticated LAN requests logged as `name -- value`),
/// so a marker anywhere else in a line must not flip stream state or fake a pair request.
pub fn scan_log_line(line: &str) -> Option<LogSignal> {
    let (ts, level, msg) = split_log_line(line)?;
    match (level, msg.trim_end()) {
        ("Info", "CLIENT CONNECTED") => Some(LogSignal::ClientConnected),
        ("Info", "CLIENT DISCONNECTED") => Some(LogSignal::ClientDisconnected),
        ("Debug", "phrase -- getservercert") => Some(LogSignal::PairRequest { received_at: ts.trim().to_string() }),
        _ => None,
    }
}

#[derive(Debug, Clone)]
struct Pending {
    request_id: u32,
}

pub struct UpstreamWebUi<H: HttpsLoopback> {
    http: H,
    seat_id: String,
    log: Option<Box<dyn LogSource>>,
    sleep: Box<dyn Fn(Duration) + Send>,
    events: VecDeque<ServerEvent>,
    pending: Option<Pending>,
    next_request_id: u32,
    stream_active: bool,
    /// Spec 70 §3.5 fallback: upstream has no audio event, so its log lines feed
    /// `split_audio::LogScanner` (anchored matches only); changes become `AudioState`.
    audio: split_audio::LogScanner,
    audio_reported: Option<split_audio::AudioState>,
    /// How long `pair_submit` waits for the new client to appear in the list.
    pub pair_poll: (u32, Duration),
}

#[derive(Deserialize)]
struct StatusOnly {
    #[serde(default)]
    status: bool,
}

#[derive(Deserialize)]
struct NamedCerts {
    #[serde(default)]
    named_certs: Vec<PairedClient>,
}

impl<H: HttpsLoopback> UpstreamWebUi<H> {
    pub fn new(http: H, seat_id: &str, log: Option<Box<dyn LogSource>>) -> Self {
        Self {
            http,
            seat_id: seat_id.into(),
            log,
            sleep: Box::new(std::thread::sleep),
            events: VecDeque::new(),
            pending: None,
            next_request_id: 1,
            stream_active: false,
            audio: split_audio::LogScanner::new(),
            audio_reported: None,
            pair_poll: (20, Duration::from_millis(500)),
        }
    }

    /// Replace the sleep used while waiting for a pairing to complete (tests).
    pub fn with_sleep(mut self, f: impl Fn(Duration) + Send + 'static) -> Self {
        self.sleep = Box::new(f);
        self
    }

    fn json<R: serde::de::DeserializeOwned>(
        &mut self,
        method: &str,
        path: &str,
        body: Option<&[u8]>,
    ) -> Result<R, StreamError> {
        let (code, bytes) = self.http.request(method, path, body)?;
        match code {
            200..=299 => {}
            401 => return Err(StreamError::WebUi("unauthorized".into())),
            403 => return Err(StreamError::WebUi("forbidden (origin_web_ui_allowed)".into())),
            c => return Err(StreamError::WebUi(format!("{method} {path}: HTTP {c}"))),
        }
        serde_json::from_slice(&bytes).map_err(|e| StreamError::WebUi(format!("{path}: bad JSON: {e}")))
    }

    fn post_status(&mut self, path: &str, body: &[u8]) -> Result<bool, StreamError> {
        Ok(self.json::<StatusOnly>("POST", path, Some(body))?.status)
    }

    fn scan_log(&mut self) {
        let Some(log) = self.log.as_mut() else { return };
        for line in log.read_new() {
            self.audio.feed(&line);
            if let Some(st) = self.audio.state()
                && self.audio_reported != Some(st)
            {
                self.audio_reported = Some(st);
                self.events.push_back(ServerEvent::AudioState { state: st.code().to_string() });
            }
            match scan_log_line(&line) {
                Some(LogSignal::ClientConnected) => {
                    self.stream_active = true;
                    self.events.push_back(ServerEvent::StreamStarted { app: None, video: None });
                }
                Some(LogSignal::ClientDisconnected) => {
                    self.stream_active = false;
                    self.events.push_back(ServerEvent::StreamEnded { reason: "client_disconnected".into() });
                }
                Some(LogSignal::PairRequest { received_at }) => {
                    // Upstream completes only the first request and Moonlight uses a fixed
                    // uniqueid, so a newer request replaces the older one (spec 80 §8.2).
                    if let Some(old) = self.pending.take() {
                        self.events
                            .push_back(ServerEvent::PairEnded { request_id: old.request_id, result: PairResult::Cancelled });
                    }
                    let request_id = self.next_request_id;
                    self.next_request_id = self.next_request_id.wrapping_add(1).max(1);
                    self.pending = Some(Pending { request_id });
                    self.events.push_back(ServerEvent::PairPending {
                        request_id,
                        client_uniqueid: String::new(),
                        device_name: String::new(),
                        received_at,
                    });
                }
                None => {}
            }
        }
    }

    fn end_pending(&mut self, result: PairResult) {
        if let Some(p) = self.pending.take() {
            self.events.push_back(ServerEvent::PairEnded { request_id: p.request_id, result });
        }
    }
}

#[derive(serde::Serialize)]
struct PinBody<'a> {
    pin: &'a str,
    name: &'a str,
}

impl<H: HttpsLoopback> SeatControl for UpstreamWebUi<H> {
    /// Proves the pinned TLS identity and the credentials with one authenticated GET.
    fn hello(&mut self, _service_version: &str) -> Result<Hello, StreamError> {
        let _: NamedCerts = self.json("GET", "/api/clients/list", None)?;
        Ok(Hello {
            protocol: 0,
            server_version: "upstream".into(),
            seat_id: self.seat_id.clone(),
            capabilities: vec!["upstream_web_ui".into()],
        })
    }

    /// Derived from the log (no HTTP polling of the server).
    fn status(&mut self) -> Result<ServerStatus, StreamError> {
        self.scan_log();
        Ok(ServerStatus {
            state: if self.stream_active { "streaming" } else { "ready" }.into(),
            stream_active: self.stream_active,
            clients_connected: u32::from(self.stream_active),
            pair_pending: self.pending.is_some(),
            ..Default::default()
        })
    }

    fn pair_submit(&mut self, request_id: Option<u32>, pin: &Secret, name: &str) -> Result<String, StreamError> {
        check_pin(pin)?;
        check_client_name(name)?;
        self.scan_log();
        // At the default `info` level upstream logs no pending-request line, so "no request
        // seen" is not proof that none waits: the PIN is submitted anyway and upstream's
        // own answer decides. Only a known, different pending request is a mismatch.
        if let (Some(want), Some(p)) = (request_id, self.pending.as_ref()) {
            if p.request_id != want {
                return Err(StreamError::NoPendingRequest);
            }
        }
        let before: Vec<String> = self.clients_list()?.into_iter().map(|c| c.uuid).collect();
        let body = Zeroizing::new(
            serde_json::to_vec(&PinBody { pin: &pin.0, name }).map_err(|e| StreamError::WebUi(e.to_string()))?,
        );
        if !self.post_status("/api/pin", &body)? {
            // Upstream answers false only when no request waits (or the PIN shape is bad,
            // which check_pin already excluded).
            self.pending = None;
            return Err(StreamError::NoPendingRequest);
        }
        let (tries, every) = self.pair_poll;
        for _ in 0..tries {
            (self.sleep)(every);
            if let Some(new) = self.clients_list()?.into_iter().find(|c| !before.contains(&c.uuid)) {
                self.end_pending(PairResult::Paired);
                return Ok(new.uuid);
            }
        }
        // The client checks the PIN; a wrong one never produces a stored certificate.
        self.end_pending(PairResult::WrongPin);
        Err(StreamError::WrongPin)
    }

    /// Upstream cannot fail a waiting request; we only forget it locally.
    fn pair_cancel(&mut self, _request_id: Option<u32>) -> Result<(), StreamError> {
        self.end_pending(PairResult::Cancelled);
        Err(StreamError::Unsupported("pair.cancel".into()))
    }

    fn clients_list(&mut self) -> Result<Vec<PairedClient>, StreamError> {
        Ok(self.json::<NamedCerts>("GET", "/api/clients/list", None)?.named_certs)
    }

    fn unpair(&mut self, uuid: &str) -> Result<(), StreamError> {
        let body = serde_json::to_vec(&serde_json::json!({ "uuid": uuid })).expect("json");
        if self.post_status("/api/clients/unpair", &body)? {
            Ok(())
        } else {
            Err(StreamError::Remote { code: "not_found".into(), detail: "no such client".into() })
        }
    }

    fn unpair_all(&mut self) -> Result<(), StreamError> {
        self.post_status("/api/clients/unpair-all", b"{}").map(drop)
    }

    /// Upstream re-reads `apps.json` only from its own save handler; the service restarts
    /// the server when no stream is active instead.
    fn apps_reload(&mut self) -> Result<u32, StreamError> {
        Err(StreamError::Unsupported("apps.reload".into()))
    }

    fn session_close(&mut self, quit_app: bool) -> Result<(), StreamError> {
        if !quit_app {
            return Err(StreamError::Unsupported("session.close without quit_app".into()));
        }
        self.post_status("/api/apps/close", b"{}").map(drop)
    }

    fn shutdown(&mut self, _grace_ms: u32) -> Result<(), StreamError> {
        Err(StreamError::Unsupported("server.shutdown".into()))
    }

    fn log_level(&mut self, _level: &str) -> Result<(), StreamError> {
        Err(StreamError::Unsupported("log.level".into()))
    }

    fn reply_mode(&mut self, _r: &serde_json::Value) -> Result<(), StreamError> {
        Err(StreamError::Unsupported("display.mode.result".into()))
    }

    fn pad_request(&mut self, _ty: &str, _body: &serde_json::Value) -> Result<(), StreamError> {
        Err(StreamError::Unsupported("pad requests".into()))
    }

    /// Non-blocking: returns what the log produced since the last call.
    fn next_event(&mut self, _timeout: Duration) -> Result<Option<ServerEvent>, StreamError> {
        if self.events.is_empty() {
            self.scan_log();
        }
        Ok(self.events.pop_front())
    }
}

