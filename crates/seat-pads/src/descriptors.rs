const DS5_PARTS: &[&[u8]] = &[DS5_HEAD, DS5_BUTTONS, DS5_TAIL];
const DS5E_PARTS: &[&[u8]] = &[DS5_HEAD, DS5E_BUTTONS, DS5_TAIL];
const DS5_LEN: usize = total(DS5_PARTS);
const DS5E_LEN: usize = total(DS5E_PARTS);
const DS5_ARR: [u8; DS5_LEN] = concat(DS5_PARTS);
const DS5E_ARR: [u8; DS5E_LEN] = concat(DS5E_PARTS);

pub const DS5_REPORT_DESCRIPTOR: &[u8] = &DS5_ARR;
pub const DS5E_REPORT_DESCRIPTOR: &[u8] = &DS5E_ARR;

