//! HID report descriptors, written for Pulsar Split from the HID 1.11 specification and
//! the public USB report layouts documented by open-source drivers (Linux
//! `hid-playstation`, SDL HIDAPI). Field offsets match `reports.rs`. `core` only: the
//! UMDF driver in `drivers/split-pad` includes this file with `#[path]`.
//!
//! Every descriptor declares one input report (id 1) whose byte layout is the public USB
//! layout of the emulated pad, one output report and the feature reports answered by
//! `features.rs`. Generic usages (X/Y/Z/Rz/Rx/Ry, hat, buttons) cover the fields that
//! DirectInput / Raw Input users need; all other bytes are vendor-defined so the length
//! matches the real pad and SDL/Steam can parse them by offset.

const fn concat<const N: usize>(parts: &[&[u8]]) -> [u8; N] {
    let mut out = [0u8; N];
    let mut at = 0;
    let mut p = 0;
    while p < parts.len() {
        let part = parts[p];
        let mut i = 0;
        while i < part.len() {
            out[at] = part[i];
            at += 1;
            i += 1;
        }
        p += 1;
    }
    assert!(at == N, "descriptor length mismatch");
    out
}

const fn total(parts: &[&[u8]]) -> usize {
    let mut n = 0;
    let mut p = 0;
    while p < parts.len() {
        n += parts[p].len();
        p += 1;
    }
    n
}

