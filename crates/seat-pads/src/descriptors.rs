/// HID class descriptor (9 bytes) for a report descriptor of `len` bytes.
pub const fn hid_descriptor(bcd_hid: u16, len: u16) -> [u8; 9] {
    [
        0x09,
        0x21,
        (bcd_hid & 0xFF) as u8,
        (bcd_hid >> 8) as u8,
        0x00, // country
        0x01, // one class descriptor
        0x22, // report
        (len & 0xFF) as u8,
        (len >> 8) as u8,
    ]
}

/// Report descriptor for a `layout::KIND_*` value.
pub const fn report_descriptor(kind: u32) -> &'static [u8] {
    match kind {
        crate::layout::KIND_XONE => XONE_REPORT_DESCRIPTOR,
        crate::layout::KIND_DS4 => DS4_REPORT_DESCRIPTOR,
        crate::layout::KIND_DS5E => DS5E_REPORT_DESCRIPTOR,
        _ => DS5_REPORT_DESCRIPTOR,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::layout::*;

    /// Minimal HID descriptor walker: returns (input bits, output bits, features) per
    /// report id for report ids used here.
    fn walk(desc: &[u8]) -> std::collections::BTreeMap<(u8, u8), u32> {
        let mut out = std::collections::BTreeMap::new();
        let (mut size, mut count, mut id) = (0u32, 0u32, 0u8);
        let mut i = 0;
        let mut depth = 0i32;
        while i < desc.len() {
            let prefix = desc[i];
            let n = match prefix & 0x03 {
                3 => 4,
                x => x as usize,
            };
            let mut v = 0u32;
            for k in 0..n {
                v |= (desc[i + 1 + k] as u32) << (8 * k);
            }
            match prefix & 0xFC {
                0x74 => size = v,
                0x94 => count = v,
                0x84 => id = v as u8,
                0x80 => *out.entry((id, 0)).or_insert(0) += size * count,
                0x90 => *out.entry((id, 1)).or_insert(0) += size * count,
                0xB0 => *out.entry((id, 2)).or_insert(0) += size * count,
                0xA0 => depth += 1,
                0xC0 => depth -= 1,
                _ => {}
            }
            i += 1 + n;
        }
        assert_eq!(depth, 0, "collections balanced");
        out
    }

    #[test]
    fn ds5_sizes() {
        for d in [DS5_REPORT_DESCRIPTOR, DS5E_REPORT_DESCRIPTOR] {
            let m = walk(d);
            assert_eq!(m[&(1, 0)], (DS_INPUT_LEN as u32 - 1) * 8, "input");
            assert_eq!(m[&(2, 1)], (DS5_OUTPUT_LEN as u32 - 1) * 8, "output");
            assert_eq!(m[&(5, 2)], 40 * 8);
            assert_eq!(m[&(9, 2)], 19 * 8);
            assert_eq!(m[&(0x20, 2)], 63 * 8);
        }
    }

    #[test]
    fn ds4_sizes() {
        let m = walk(DS4_REPORT_DESCRIPTOR);
        assert_eq!(m[&(1, 0)], 63 * 8);
        assert_eq!(m[&(5, 1)], 31 * 8);
        assert_eq!(m[&(2, 2)], 36 * 8);
        assert_eq!(m[&(0x12, 2)], 15 * 8);
        assert_eq!(m[&(0x81, 2)], 6 * 8);
        assert_eq!(m[&(0xA3, 2)], 48 * 8);
    }

    #[test]
    fn xone_sizes() {
        let m = walk(XONE_REPORT_DESCRIPTOR);
        assert_eq!(m[&(1, 0)], (XONE_INPUT_LEN as u32 - 1) * 8);
        assert_eq!(m[&(3, 1)], (XONE_OUTPUT_LEN as u32 - 1) * 8);
    }

    #[test]
    fn hid_descriptor_bytes() {
        let d = hid_descriptor(0x0111, DS5_REPORT_DESCRIPTOR.len() as u16);
        assert_eq!(d[0], 9);
        assert_eq!(u16::from_le_bytes([d[7], d[8]]) as usize, DS5_REPORT_DESCRIPTOR.len());
    }
}
