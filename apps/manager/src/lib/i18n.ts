/** Turkish text for a package reason code; unknown codes fall back to a generic text. */
export function failureText(reason: string | null | undefined): string {
  if (!reason) return t.failure.unsupported;
  return t.failure[reason] ?? errorText[reason as ErrorCode] ?? `${errorText.internal} (${reason})`;
}

export function isProtoError(e: unknown): e is ProtoError {
  return typeof e === 'object' && e !== null && 'code' in e && typeof (e as ProtoError).code === 'string';
}

/** Turkish text for any error thrown by the API layer. */
export function errorMessage(e: unknown): string {
  if (!isProtoError(e)) return errorText.internal;
  if (e.reason && t.failure[e.reason]) return t.failure[e.reason];
  if (e.code === 'duplicate_name' && e.field === 'display_name') return fieldErrorText.display_name_duplicate;
  return errorText[e.code] ?? errorText.internal;
}
